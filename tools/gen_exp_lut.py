"""Generate the RTL exp LUT as a synthesizable Verilog function.

LUT[i] = round(exp(-i / 16) * 32767), i = 0..255
Index is derived as (delta_int >> 4) where delta_int = (max - score) in units
of 1/256, so each LUT step covers 16/256 = 1/16 in real value.
"""
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'rtl', 'kwt_exp_lut.v')

N = 256
vals = [int(round(np.exp(-i / 16.0) * 32767)) for i in range(N)]
vals = [max(0, min(32767, v)) for v in vals]

lines = []
lines.append('`timescale 1ns / 1ps')
lines.append('// AUTO-GENERATED by tools/gen_exp_lut.py -- do not edit')
lines.append('// LUT[i] = round(exp(-i/16) * 32767), i = 0..255')
lines.append('module kwt_exp_lut (')
lines.append('    input  wire [7:0]  idx,')
lines.append('    output reg  [15:0] val')
lines.append(');')
lines.append('    always @(*) begin')
lines.append('        case (idx)')
for i, v in enumerate(vals):
    lines.append("            8'd%-3d: val = 16'd%d;" % (i, v))
lines.append("            default: val = 16'd0;")
lines.append('        endcase')
lines.append('    end')
lines.append('endmodule')
lines.append('')

with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('\n'.join(lines))

print('wrote %s (%d entries)' % (OUT, N))
print('LUT[0]=%d LUT[1]=%d LUT[16]=%d LUT[64]=%d LUT[255]=%d' % (
    vals[0], vals[1], vals[16], vals[64], vals[255]))
